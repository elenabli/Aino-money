PRODUCT_RULES = tuple((category, re.compile(pattern, re.I)) for category, pattern in RULES)


def product_category(name: str, group: str) -> str:
    for category, pattern in PRODUCT_RULES:
        if pattern.search(name):
            return category
    return "Other groceries" if group == "Food" else "Other merchandise"
